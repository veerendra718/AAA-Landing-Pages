type Entry = [name: string, rank: string, college: string];

function list(slug: string, entries: Entry[]): Achiever[] {
  return entries.map(([name, rank, college], i) => ({
    name,
    rank,
    college,
    image: `/images/landing/achievers/brochure/${slug}-${String(i + 1).padStart(2, "0")}.jpg`,
  }));
}

